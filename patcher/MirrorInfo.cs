// Cutscene mirror: what each object looks like on screen, worked out from its Draw event at patch time.
//
// In a shared story cutscene only the leader's game plays it; the others draw what the leader's
// game shows, from a list of sprites it sends every frame (scr_mp_mirror). For each instance the
// leader needs to know what the instance actually draws:
//   kind 0  no Draw event: the game draws its sprite (draw_self)
//   kind 1  its Draw event draws its own sprite: same as 0, or, when the drawing call's arguments
//           only use things that always exist on the instance, those exact arguments (a generated
//           function per object, mp_mie_<object>, returning [sprite, frame, x, y, xscale, yscale,
//           angle, colour, alpha]; kind 3) - e.g. a fade stretched over the screen, a shake offset
//   kind 2  its Draw event draws something else (text, shapes, nothing): not sent
// The result is a generated script, scr_mp_mirrorinfo, with mp_mirror_info_init().
using System.Text;
using System.Text.RegularExpressions;
using UndertaleModLib;
using UndertaleModLib.Models;

static class MirrorInfo
{
    static readonly Regex DrawCall = new(@"\b(draw_self|draw_sprite_ext|draw_sprite)\s*\(", RegexOptions.Compiled);
    static readonly Regex Ident = new(@"(?<![\w.""])([A-Za-z_]\w*)(\s*\()?", RegexOptions.Compiled);
    static readonly Regex VarDecl = new(@"\bvar\s+([^;]+);", RegexOptions.Compiled);
    static readonly Regex Assign = new(@"(?m)^\s*(?:self\.)?([A-Za-z_]\w*)\s*(?:\[[^\]]*\])?\s*(?:=|\+=|-=|\*=|/=)", RegexOptions.Compiled);

    static readonly HashSet<string> Builtins = new()
    {
        "x", "y", "xstart", "ystart", "xprevious", "yprevious", "sprite_index", "image_index", "image_xscale",
        "image_yscale", "image_angle", "image_blend", "image_alpha", "image_speed", "image_number", "depth",
        "visible", "direction", "speed", "hspeed", "vspeed", "sprite_width", "sprite_height", "sprite_xoffset",
        "sprite_yoffset", "bbox_left", "bbox_right", "bbox_top", "bbox_bottom", "id", "object_index", "room",
        "current_time", "pi", "true", "false", "noone", "undefined", "self", "global", "div", "mod", "and", "or", "not", "xor"
    };

    public static string Generate(UndertaleData data, Func<UndertaleCode, string> decompile, out int counted)
    {
        var assets = new HashSet<string>();
        foreach (var s in data.Sprites) assets.Add(s.Name.Content);
        foreach (var s in data.GameObjects) assets.Add(s.Name.Content);
        foreach (var s in data.Sounds) assets.Add(s.Name.Content);
        var decomp = new Dictionary<string, string>();
        string Code(string name)
        {
            if (decomp.TryGetValue(name, out var t)) return t;
            var c = data.Code.ByName(name);
            t = null;
            if (c != null)
            {
                try { t = decompile(c).Replace("\r", ""); } catch { t = null; }
            }
            decomp[name] = t;
            return t;
        }

        var sb = new StringBuilder();
        var funcs = new StringBuilder();
        sb.AppendLine("// Generated by the patcher (MirrorInfo.cs). Do not edit.");
        sb.AppendLine("function mp_mirror_info_init()");
        sb.AppendLine("{");
        sb.AppendLine($"    global.mp_mi_kind = array_create({data.GameObjects.Count + 64}, 0);");
        sb.AppendLine($"    global.mp_mi_eval = array_create({data.GameObjects.Count + 64}, -1);");
        counted = 0;
        foreach (var obj in data.GameObjects)
        {
            string name = obj.Name.Content;
            if (name.StartsWith("obj_mp_")) continue;
            // The Draw event that applies: its own, or the nearest ancestor's.
            string draw = null;
            UndertaleGameObject drawOwner = null;
            var seen = new HashSet<UndertaleGameObject>();
            for (var o = obj; o != null && seen.Add(o); o = o.ParentId)
            {
                var t = Code("gml_Object_" + o.Name.Content + "_Draw_0");
                if (t == null) continue;
                // Only calls the parent's: keep looking up.
                if (!DrawCall.IsMatch(t) && t.Contains("event_inherited")) continue;
                draw = t;
                drawOwner = o;
                break;
            }
            if (draw == null)
                continue; // kind 0 (default)
            // The call that draws the object itself: the first one outside any condition, or else
            // the first conditional one that draws the object's own sprite (a palette/no-palette
            // pair, say) - never a one-off effect sprite drawn only now and then.
            Match m = null;
            List<string> args = null;
            foreach (Match cm in DrawCall.Matches(draw))
            {
                int o2 = cm.Index + cm.Length;
                int c2 = MatchParen(draw, o2 - 1);
                if (c2 < 0) continue;
                var a2 = SplitArgs(draw.Substring(o2, c2 - o2));
                bool own = cm.Groups[1].Value == "draw_self" || (a2.Count > 0 && a2[0].Trim() == "sprite_index");
                if (Depth(draw, cm.Index) == 0)
                {
                    m = cm;
                    args = a2;
                    break;
                }
                if (own && m == null)
                {
                    m = cm;
                    args = a2;
                }
            }
            if (m == null)
            {
                sb.AppendLine($"    global.mp_mi_kind[{name}] = 2;");
                counted++;
                continue;
            }
            string fn = m.Groups[1].Value;
            string[] full = null;
            if (fn == "draw_sprite_ext" && args.Count == 9)
                full = args.Select(a => a.Trim()).ToArray();
            else if (fn == "draw_sprite" && args.Count == 4)
                full = new[] { args[0].Trim(), args[1].Trim(), args[2].Trim(), args[3].Trim(), "1", "1", "0", "c_white", "1" };
            sb.AppendLine($"    global.mp_mi_kind[{name}] = 1;");
            counted++;
            if (full == null || Regex.IsMatch(draw.Substring(0, m.Index), @"\bwith\s*\("))
                continue;
            // The exact arguments, when every name in them is sure to exist on the instance.
            var known = new HashSet<string>(Builtins);
            var locals = new HashSet<string>();
            foreach (Match vd in VarDecl.Matches(draw))
                foreach (var part in vd.Groups[1].Value.Split(','))
                {
                    var nm = part.Split('=')[0].Trim();
                    if (nm.Length > 0) locals.Add(nm);
                }
            var seen2 = new HashSet<UndertaleGameObject>();
            for (var o = obj; o != null && seen2.Add(o); o = o.ParentId)
            {
                var ct = Code("gml_Object_" + o.Name.Content + "_Create_0");
                if (ct == null) continue;
                var cl = new HashSet<string>();
                foreach (Match vd in VarDecl.Matches(ct))
                    foreach (var part in vd.Groups[1].Value.Split(','))
                        cl.Add(part.Split('=')[0].Trim());
                // Only assignments at the top level of Create count (not inside an if).
                foreach (var line in TopLevelLines(ct))
                {
                    var am = Assign.Match(line);
                    if (am.Success && !cl.Contains(am.Groups[1].Value))
                        known.Add(am.Groups[1].Value);
                }
                // A Create event that doesn't call its parent's: the parent's never runs.
                if (!ct.Contains("event_inherited"))
                    break;
            }
            bool ok = true;
            foreach (var a in full)
            {
                if (a.Contains("other.") || a.Contains("e__") || a.Contains("argument") || a.Contains("\"")) { ok = false; break; }
                foreach (Match im in Ident.Matches(a))
                {
                    string id = im.Groups[1].Value;
                    if (im.Groups[2].Success) continue; // a function call
                    if (a.Length > im.Index && im.Index > 0 && a[im.Index - 1] == '.') continue;
                    if (locals.Contains(id)) { ok = false; break; }
                    if (known.Contains(id) || assets.Contains(id) || id.StartsWith("c_") || id.StartsWith("bm_") || id.StartsWith("fa_")) continue;
                    ok = false;
                    break;
                }
                if (!ok) break;
            }
            if (!ok) continue;
            // global.* is fine only when it's a whole name (global.darkzone), which Ident skips.
            funcs.AppendLine($"function mp_mie_{name}()");
            funcs.AppendLine("{");
            funcs.AppendLine($"    return [{string.Join(", ", full)}];");
            funcs.AppendLine("}");
            funcs.AppendLine();
            sb.AppendLine($"    global.mp_mi_kind[{name}] = 3;");
            sb.AppendLine($"    global.mp_mi_eval[{name}] = mp_mie_{name};");
        }
        sb.AppendLine("}");
        sb.AppendLine();
        sb.Append(funcs);
        return sb.ToString();
    }

    // Index of the ")" matching the "(" at position i, or -1.
    static int MatchParen(string s, int i)
    {
        int d = 0;
        bool str = false;
        for (int k = i; k < s.Length; k++)
        {
            char c = s[k];
            if (c == '"') str = !str;
            if (str) continue;
            if (c == '(' || c == '[') d++;
            else if (c == ')' || c == ']')
            {
                d--;
                if (d == 0) return k;
            }
        }
        return -1;
    }

    static List<string> SplitArgs(string s)
    {
        var res = new List<string>();
        int d = 0, start = 0;
        bool str = false;
        for (int k = 0; k < s.Length; k++)
        {
            char c = s[k];
            if (c == '"') str = !str;
            if (str) continue;
            if (c == '(' || c == '[' || c == '{') d++;
            else if (c == ')' || c == ']' || c == '}') d--;
            else if (c == ',' && d == 0)
            {
                res.Add(s.Substring(start, k - start));
                start = k + 1;
            }
        }
        if (s.Trim().Length > 0) res.Add(s.Substring(start));
        return res;
    }

    // Brace depth at position pos (code blocks the call is inside).
    static int Depth(string s, int pos)
    {
        int d = 0;
        bool str = false;
        for (int k = 0; k < pos; k++)
        {
            char c = s[k];
            if (c == '"') str = !str;
            if (str) continue;
            if (c == '{') d++;
            else if (c == '}') d--;
        }
        return d;
    }

    static IEnumerable<string> TopLevelLines(string s)
    {
        int d = 0;
        foreach (var line in s.Split('\n'))
        {
            if (d == 0) yield return line;
            foreach (char c in line)
            {
                if (c == '{') d++;
                else if (c == '}') d--;
            }
        }
    }
}
