        static readonly string[] HeartRows = { ".##.##.", "#######", "#######", ".#####.", "..###..", "...#..." };

        // Width of a text at a pixel size, with `gap` pixels between letters.
        public static float Width(string text, float px, float gap)
        {
            if (text.Length == 0) return 0;
            return text.Length * (5 * px + gap) - gap;
        }

        public static void Draw(Graphics g, string text, float x, float y, float px, float gap, Color c, bool center)
        {
            if (center) x -= Width(text, px, gap) / 2;
            using (var b = new SolidBrush(c))
            {
                foreach (var ch in text.ToUpperInvariant())
                {
                    if (Glyphs.TryGetValue(ch, out var rows))
                        for (int r = 0; r < 7; r++)
                            for (int col = 0; col < 5; col++)
                                if (rows[r][col] == '#') g.FillRectangle(b, x + col * px, y + r * px, px, px);
                    x += 5 * px + gap;
                }
            }
        }

        public static void Heart(Graphics g, float x, float y, float px, Color c)
        {
            using (var b = new SolidBrush(c))
                for (int r = 0; r < HeartRows.Length; r++)
                    for (int col = 0; col < 7; col++)
                        if (HeartRows[r][col] == '#') g.FillRectangle(b, x + col * px, y + r * px, px, px);
        }
